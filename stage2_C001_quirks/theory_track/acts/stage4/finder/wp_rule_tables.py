"""Generate the frozen-input tables of WP_RULE.md (appendix A) from data/acts_stage4/fix_r4/f4r_admissibility.json
(plan §2.6), and the sha256 table of the code the rule refers to.  Exact transcription by code: no number is typed.
Run (theory_track): pixi run python -m acts.stage4.finder.wp_rule_tables  -> acts/stage4/WP_RULE_tables.md
Fix WP_RULE R1: also the dilution-aware e_adm table (A.2b, from data/acts_stage4/frozen/eadm_dilution.json), the frozen
inputs (A.4); the tables are pasted into WP_RULE.md (from the generated marker to the end of the file), then
data/acts_stage4/frozen/frozen_inputs.json is written with the sha256 of the resulting WP_RULE.md.
Fix WP_RULE R2: mip_gev is read from G1's data/acts_stage4/g1/v49/v49.json (mip_unit.mip_gev_pooled_truncated, the frozen
pooled definition; closure checked), the SR-T in-job status is 'implemented', the PU-density trigger is 1.05.
"""
import hashlib
import json
import math

from .trials import TT

ADM = TT / 'data' / 'acts_stage4' / 'fix_r4' / 'f4r_admissibility.json'
OUT = TT / 'acts' / 'stage4' / 'WP_RULE_tables.md'
WPR = TT / 'acts' / 'stage4' / 'WP_RULE.md'
EADM = TT / 'data' / 'acts_stage4' / 'frozen' / 'eadm_dilution.json'
FROZ = TT / 'data' / 'acts_stage4' / 'frozen' / 'frozen_inputs.json'
V49 = TT / 'data' / 'acts_stage4' / 'g1' / 'v49' / 'v49.json'
MARK = '<!-- generated by acts/stage4/finder/wp_rule_tables.py'
HASHED = ['acts/stage4/finder/finder.py', 'acts/stage4/finder/kernels.py', 'acts/stage4/finder/weights.py',
          'acts/stage4/finder/production.py', 'acts/stage4/finder/pu_inputs.py', 'acts/stage4/finder/chain_inputs.py',
          'acts/stage4/run_stage4.py', 'acts/stage4/code/run_chain.py', 'acts/stage4/code/eloss.py',
          'acts/stage4/code/pu_chain_interim.py', 'acts/stage4/probes/f4r_admissibility.py',
          'data/acts_stage4/fix_r4/f4r_admissibility.json', 'sim/stage3/results/P2.json',
          'data/acts_stage4/review_r1_constructive/r1c_signal_handles.json',
          'acts/stage4/finder/eadm_dilution.py', 'data/acts_stage4/frozen/eadm_dilution.json',
          'data/sim_stage3/STAGE3_INDEX.json',
          'data/acts_stage4/review_wp1/r1_inputs.py', 'data/acts_stage4/review_wp1/r1_inputs.json',
          'data/acts_stage4/g1/v49/v49.json', 'acts/stage4/plan.md']
# frozen numeric inputs (WP_RULE.md §1.2, §1.3, §1.4, §8, §10); mip_gev from v49.json (mip_inputs below)
FROZEN_VALUES = dict(delta95=0.15, eta_max=1.0, betagamma_mu=92.0, trunc_frac=0.6, e_levels=[1.3, 1.6, 2.0],
                     admissibility_margin=1.25, pu_density_update_trigger=1.05, f_ckf_cut=0.2, f_ckf_B_PU_credit=1.0, t_seed=6, w_c_mm=75.0,
                     t_tol_mm=0.030, nsub=64, f_lo=1.0, f_hi=1.0,
                     sr_t=dict(sigma_t_ps=35.0, sigma_t_variation_ps=60.0, dt_acc_ns=25.0, dt_acc_variation_ns=12.5,
                               overlay_bx=[-12, 3], late_rate_threshold=1e-4, t_min='from B1 + overlay by the frozen rule',
                               in_job_btl_presence='implemented + validated (fix WP_RULE R2): production.process_trial('
                                                   'btl=, require_btl=), columns RUNGS_T = r & BTL-present; required '
                                                   'for every rho > 1 production job'))


def mip_inputs():
    """F-2 (WP_RULE §1.4): the pooled 0.6-truncated mean of G1's V4-9 muon gun, after the <= 3 % sampler closure."""
    m = json.loads(V49.read_text())['mip_unit']
    assert m['closure_pass_3pct'] and abs(m['sampler_over_fatras_pooled'] - 1.0) <= 0.03, 'B-2 sampler closure failed'
    v = float(m['mip_gev_pooled_truncated'])
    assert abs(v - 3.5582e-4) < 1e-8, v
    return dict(mip_gev=v, mip_status='FILLED (G1 V4-9, fix WP_RULE R2)',
                mip_source='data/acts_stage4/g1/v49/v49.json -> mip_unit.mip_gev_pooled_truncated',
                mip_n_tracks=int(m['n_tracks']), mip_n_pooled_hits=int(m['n_pooled_hits']),
                mip_sampler_over_fatras_pooled=float(m['sampler_over_fatras_pooled']),
                mip_gev_track_median_diagnostic=float(m['mip_gev_track_median']),
                betagamma_mu_g1_measured=float(m['muon_betagamma_median']),
                betagamma_mu_note='F-3 keeps the generator-level 92 (median of the gun definition); the G1 track '
                                  'median 90.7 (tracks with >= 1 TBPX hit) is a cross-check: R_eff <= 0.09 %, no e_adm '
                                  'cell changes (review WP_RULE R2 C-1)')


def sha(p):
    h = hashlib.sha256()
    h.update((TT / p).read_bytes())
    return h.hexdigest()


def main():
    d = json.loads(ADM.read_text())
    L = []
    L.append('<!-- generated by acts/stage4/finder/wp_rule_tables.py from f4r_admissibility.json; do not edit -->')
    L.append('### A.1 Smoothed Λ_R(m) and the width admissibility thresholds (plan §2.6)\n')
    L.append('k_adm(m, Λ) = the largest k ∈ {0, …, 4} with Λ ≥ Λ_R(m)·2^{(k+1)/2}; the columns give Λ_R·2^{(k+1)/2} '
             '(keV): Λ at or above the column value admits width rung k (w_core < W_c/2^k); below the k = 1 column, '
             'k_adm = 0 (no width cut).\n')
    L.append('| species-mass | Λ_R smoothed (keV) | form | per-mass Λ_R (keV) | k ≥ 1 | k ≥ 2 | k ≥ 3 | k ≥ 4 |')
    L.append('|---|---|---|---|---|---|---|---|')
    for sp, v in d['Lambda_R'].items():
        lr = v['smoothed_keV']
        thr = [lr * 2 ** ((k + 1) / 2) for k in (1, 2, 3, 4)]
        L.append(f"| {sp} | {lr:.4f} | {v['smoothing_form']} | {v['per_mass_keV']:.4f} | "
                 + ' | '.join(f'{t:.3f}' for t in thr) + ' |')
    for sp, v in d['Lambda_R'].items():          # consistency with the JSON's own thresholds (= Λ_R·2^{(k+1)/2})
        for k in (1, 2, 3, 4):
            assert abs(v['k_thresholds_keV'][f'k>={k}'] - v['smoothed_keV'] * 2 ** ((k + 1) / 2)) < 2e-3, (sp, k)
    L.append('\n(Identical, to the JSON rounding, to `k_thresholds_keV` "k>=k" of f4r_admissibility.json, which already '
             'includes the one-rung margin; checked by the generator.)\n')
    L.append('### A.2 βγ_IT(m) (median over the p2 Λ points) and the per-point medians used by the max rule\n')
    L.append('βγ_IT(m, Λ) = max(βγ_IT(m), per-point median at Λ).\n')
    lams = sorted({float(l) for v in d['betagamma_IT'].values() for l in v['per_Lambda']})
    L.append('| species-mass | βγ_IT(m) | ' + ' | '.join(f'{l:g}' for l in lams) + ' |')
    L.append('|---|---|' + '---|' * len(lams))
    for sp, v in d['betagamma_IT'].items():
        pl = {float(k): x for k, x in v['per_Lambda'].items()}
        L.append(f"| {sp} | {v['betagamma_IT']:.3f} | " + ' | '.join(f'{pl[l]:.3f}' if l in pl else '—' for l in lams) + ' |')
    # ---- A.2b dilution-aware e_adm (fix WP_RULE R1 B-1)
    ea = json.loads(EADM.read_text())
    L.append('\n### A.2b Dilution-aware dE/dx admissibility e_adm(m, Λ) (§8; `eadm_dilution.json`)\n')
    L.append('Cell = k_adm / e_adm (MIP; "–" = none). R_eff/1.25 ≥ e. Model inputs: η_max = %g, βγ_μ = %g, μ_c = %s, '
             'X_l = %s mm, %d toys, seed %d, pooled unit %.4f.\n' % (ea['eta_max'], ea['bg_mu'], ea['mu_c'],
                                                                     ea['x_l_mm'], ea['ntoy'], ea['seed'],
                                                                     ea['unit_estimator']))
    lams2 = sorted({float(l) for v in ea['e_adm'].values() for l in v})
    L.append('| species-mass | ' + ' | '.join(f'{l:g}' for l in lams2) + ' |')
    L.append('|---|' + '---|' * len(lams2))
    for sp, v in ea['e_adm'].items():
        pl = {float(k): x for k, x in v.items()}
        L.append(f'| {sp} | ' + ' | '.join((f"{pl[l]['k_adm']}/" + (f"{pl[l]['e_adm']:g}" if pl[l]['e_adm'] else '–'))
                                          if l in pl else '' for l in lams2) + ' |')
    L.append('\n### A.3 Hashes (sha256) of the inputs and of the code this rule refers to\n')
    L.append('| file | sha256 |')
    L.append('|---|---|')
    for p in HASHED:
        L.append(f'| `{p}` | `{sha(p)}` |')
    L.append(f"\nf4r inputs as recorded in the JSON: {json.dumps(d['inputs']['P2.json_sha256'])} (P2.json), "
             f"{json.dumps(d['inputs']['r1c_signal_handles.json_sha256'])} (r1c).\n")
    L.append('### A.4 Frozen numeric inputs (`data/acts_stage4/frozen/frozen_inputs.json`)\n')
    L.append('| input | value |')
    L.append('|---|---|')
    for k, v in FROZEN_VALUES.items():
        L.append(f'| {k} | {json.dumps(v, ensure_ascii=False)} |')
    mi = mip_inputs()
    L.append(f"| mip_gev | {mi['mip_gev']!r} GeV (= 3.5582·10⁻⁴; pooled 0.6-truncated mean of the V4-9 muon-gun TBPX "
             f"deposits, §1.4; `v49.json`, {mi['mip_n_tracks']} tracks, sampler/Fatras "
             f"{mi['mip_sampler_over_fatras_pooled']:.5f}) |")
    L.append(f"| betagamma_mu_g1_measured | {mi['betagamma_mu_g1_measured']:.2f} (cross-check only; F-3 = 92) |")
    L.append('\nThe orchestrator freezes by setting `frozen = true` (after the final hash regeneration) and copying the '
             'file to `acts/stage4/frozen_inputs.json`, which `run_stage4.py` reads.\n')
    txt = '\n'.join(L) + '\n'
    OUT.write_text(txt)
    w = WPR.read_text()
    i = w.index(MARK)
    WPR.write_text(w[:i] + txt)
    fz = dict(frozen=False, status='FREEZE CANDIDATE (fix WP_RULE R2); all inputs filled',
              **FROZEN_VALUES, finder_config=dict(road=FROZEN_VALUES['delta95']),
              **mi,
              mip_definition='pooled 0.6-truncated mean of the path-corrected (x r_xy/|u|) TBPX deposits of all hits of '
                             'the V4-9 muon gun (>= 1e4 mu, pT U[1,10] GeV, eta U[-2.5,2.5]), same Fatras/digi/slab '
                             'config as PU; GeV',
              eadm=ea['e_adm'] and {sp: {l: r['e_adm'] for l, r in v.items()} for sp, v in ea['e_adm'].items()},
              wp_rule_path='acts/stage4/WP_RULE.md', wp_rule_sha256=sha('acts/stage4/WP_RULE.md'),
              sha256={p: sha(p) for p in HASHED})
    FROZ.write_text(json.dumps(fz, indent=1))
    print(OUT, WPR, FROZ)


if __name__ == '__main__':
    main()
