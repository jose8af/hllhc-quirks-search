"""val_headlines.py -- generate the VALIDATION.md §0 summary from results/*.json (review S2-R1 A2; fixer 2026-10-11), so that
no headline number can go stale.  Every range below is min..max over the listed points, read from the JSON.
Review S2-R2 C-3/C-4/C-5/C-7: the TRGS weight ratio, the pull/σ statements and the nominal-PASS statement are now computed
(results/trgs_stats.json from scripts/val_trgs_stats.py; interp/shower/mlm/qed_fsr.json); the E-TRG exclusion from the DJR
ranges is stated with its number; the QED-FSR shifts carry their bootstrap errors; the template/toy pull is quoted.
Hard-coded external inputs that stay text: γγ +4.0-4.2 % and Sommerfeld +5-15 % (T6/TH, not computed in Stage 2).
Run: pixi run -e ana python scripts/val_headlines.py   -> rewrites the block between the AUTO-HEADLINES markers in VALIDATION.md
and writes results/headlines.md."""
import json
import os

SIM = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(SIM, 'results')
J = lambda n: json.load(open(os.path.join(RES, n)))
BEGIN = '<!-- BEGIN AUTO-HEADLINES (generated by scripts/val_headlines.py from results/*.json; do not edit by hand) -->'
END = '<!-- END AUTO-HEADLINES -->'
PTS = ['F_200', 'F_500', 'F_1000', 'S_200', 'S_500', 'S_1000']


def pc(x, d=1, sign=True):
    return f'{100 * x:+.{d}f}' if sign else f'{100 * x:.{d}f}'


def rng(vals, d=1, sign=True):
    return f'{pc(min(vals), d, sign)}…{pc(max(vals), d, sign)} %'


def main():
    X, Sp, L, M, T, O, Sh, I, Q, RR = (J(n) for n in ('xsec.json', 'spectra.json', 'lmax_bias.json', 'mlm.json', 'tune.json',
                                                     'loader.json', 'shower.json', 'interp.json', 'qed_fsr.json', 'reshower_repro.json'))
    TS = J('trgs_stats.json')
    out = []
    a = out.append
    # 1 cross sections
    lo = [r['ratio'] - 1 for r in X['lo_vs_appA']['rows']]
    th = [r['ratio_to_th'] - 1 for r in X['normalisation_E']['rows'].values() if r['ratio_to_th']]
    ew_a = [r['ratio_a'] - 1 for r in X['ew_scheme']['rows']]; ew_b = [r['ratio_b'] - 1 for r in X['ew_scheme']['rows']]
    b = X['bands']['rows']
    a('1. **Cross sections.**')
    a(f'   - LO σ (MG, hand-written UFO) vs App. A / TH §2.3 after α rescaling: {rng(lo)} for E and Ẽ at 200/500/1000 GeV; '
      f'FeynRules vs hand-written UFO {pc(X["fr_vs_hw"]["ratio_E"] - 1, 2)} % (E), {pc(X["fr_vs_hw"]["ratio_S"] - 1, 2)} % (Ẽ). '
      '**VERIFIED** (two codes).')
    a(f'   - σ_norm = N_IC × K_WG × LO(α = 1/127.9) reproduces the TH §2.3 table to {rng(th, 2)} at the {len(th)} table masses in '
      '200-1200 GeV. This checks the LO part and the K interpolation only: K itself is transcribed from TH (**UNVERIFIED** for '
      'E and Ẽ alike). K beyond 1200 GeV is extrapolated (**ESTIMATE**, ±2 %).')
    a(f'   - LO scale band (E LOPS, 9-point): +{b["F_200_LOPS"]["scale_up_pct"]:.1f}/{b["F_200_LOPS"]["scale_dn_pct"]:.1f}, '
      f'+{b["F_500_LOPS"]["scale_up_pct"]:.1f}/{b["F_500_LOPS"]["scale_dn_pct"]:.1f}, +{b["F_1000_LOPS"]["scale_up_pct"]:.1f}/'
      f'{b["F_1000_LOPS"]["scale_dn_pct"]:.1f} % at 200/500/1000 GeV, as in TH (**VERIFIED**).')
    a(f'   - EW scheme: the LO ratio α(M_Z)/Gμ is {rng(ew_b)} (pure α rescaling) and {rng(ew_a)} (consistent α(M_Z) scheme). '
      'This checks the α rescaling of the LO used in σ_norm; it is **not** the uncertainty of σ_norm, which inherits the WG '
      'scheme through K_WG. The yield nuisance is TH\'s **±5 %** (K transfer + scheme, ESTIMATE) (§1.3).')
    a('   - Not in σ_norm: inelastic γγ (+4.0-4.2 %), Sommerfeld (+5-15 %), NLO EW (−few %, UNVERIFIED) (SAMPLES.md box).')
    # 2 spectra
    inc = [P['incl'][k]['median_ratio_to_old']['gm1'] - 1 for P in Sp['points'].values() for k in P['incl'] if k.startswith('MG_')]
    tl = [P['tail'][k]['median_ratio_to_old']['gm1'] for P in Sp['points'].values() for k in ('MG_TRGS', 'MG_INC') if k in P['tail']]
    tm = [P['tail'][k]['median_ratio_to_old']['M'] for P in Sp['points'].values() for k in ('MG_TRGS', 'MG_INC') if k in P['tail']]
    a('2. **Spectra vs the old generator (ESTIMATE: single generator each; measured differences).**')
    a(f'   - Inclusive median of γ*−1: MG/old − 1 = {rng(inc)} (criterion 2 %: {"PASS" if max(abs(u) for u in inc) < 0.02 else "FAIL"}).')
    a(f'   - Tail (pT > 200, |y| < 3.5): MG/old medians of γ*−1 {min(tl):.3f}-{max(tl):.3f}, of m(QQ̄) {min(tm):.3f}-{max(tm):.3f}.')
    # 3 lmax
    B = {p: L['points'][p]['bias_vs_iv'] for p in PTS}
    g = lambda k, q: [B[p][k][q] for p in PTS]
    sb = [L['points'][p]['syst_budget']['x']['total'] for p in PTS]
    sbn = [L['points'][p]['syst_budget']['nosc']['total'] for p in PTS]
    a('3. **ISR tail and ℓ_max bias, S-13 (ESTIMATE: LO-MLM + Pythia CP5, single generator).**')
    a(f'   - Fixed-pT ISR trick, like-for-like (|η| < 2.5 on both sides, (i\') vs (iv)): median ℓ_max biased by '
      + ' / '.join(f'{pc(B[p]["ip_fixedpt_MGLO_eta25"]["lmax_median_bias"], 0)}' for p in PTS[:3]) + ' % (E) and '
      + ' / '.join(f'{pc(B[p]["ip_fixedpt_MGLO_eta25"]["lmax_median_bias"], 0)}' for p in PTS[3:]) + ' % (Ẽ) at 200/500/1000 GeV; '
      f'N_osc by {rng(g("ip_fixedpt_MGLO_eta25", "nosc_median_bias"), 0)}.')
    a(f'   - T2 §3 definition (no η cut on either side): ℓ_max {rng(g("i_fixedpt_MGLO_vs_iv_noeta", "lmax_median_bias"), 0)}, '
      f'N_osc {rng(g("i_fixedpt_MGLO_vs_iv_noeta", "nosc_median_bias"), 0)}. The mixed comparison of the first draft '
      f'(no η cut for (i), |η| < 2.5 for (iv)) gives N_osc {rng(g("i_fixedpt_MGLO", "nosc_median_bias") + g("i_fixedpt_oldcache", "nosc_median_bias"), 1)}: '
      'no sign-definite bias at 1 TeV.')
    a(f'   - The old T2 LO V*+jet generator: ℓ_max {rng(g("ii_T2_Vjet", "lmax_median_bias"))}, N_osc {rng(g("ii_T2_Vjet", "nosc_median_bias"))}.')
    a(f'   - Uncertainty of the reference medians (stat ⊕ 9-pt scale ⊕ merging ⊕ Pythia shower ⊕ ME α_s): ℓ_max ±{min(sb) * 100:.1f}…'
      f'{max(sb) * 100:.1f} %, N_osc ±{min(sbn) * 100:.1f}…{max(sbn) * 100:.1f} %, dominated by the (statistically limited) merging '
      'envelope. Not included: QED FSR off the quirks (item 9).')
    # 4 MLM
    # E-TRG (ME cut pT(QQ)_ME >= 100 GeV) is excluded from the DJR ranges: the generation cut sculpts d01 around qCut (C-4)
    dj = {k: v for k, v in M['djr'].items() if v and not k.startswith('E-TRG')}
    xtrg = {k: v for k, v in M['djr'].items() if v and k.startswith('E-TRG')}
    nom_fail = [k for k, v in dj.items() if not k.startswith('V-MERGE')
                for var in ('log10d01', 'log10d12') if not v[var]['step_at_qcut']['PASS_10pct']]
    d01 = [v['log10d01']['max_dev_near_qcut'] for v in dj.values()]; d12 = [v['log10d12']['max_dev_near_qcut'] for v in dj.values()]
    st01 = [v['log10d01']['step_at_qcut']['disc'] for v in dj.values()]; st12 = [v['log10d12']['step_at_qcut']['disc'] for v in dj.values()]
    fails = [f'{k} {var[5:]} ({pc(v[var]["step_at_qcut"]["disc"], 1)} ± {100 * v[var]["step_at_qcut"]["disc_err"]:.1f} %)'
             for k, v in dj.items() for var in ('log10d01', 'log10d12') if not v[var]['step_at_qcut']['PASS_10pct']]
    pfails = [f'{k} {var[5:]} ({100 * v[var]["max_dev_near_qcut"]:.1f} %)' for k, v in dj.items() for var in ('log10d01', 'log10d12')
              if v[var]['max_dev_near_qcut'] > 0.10]
    qv = M['qcut_variation_m500']; f0 = qv['xqcut30_qcut45']['f_pt200']
    fv = [qv[k]['f_pt200'] / f0 - 1 for k in qv if k != 'xqcut30_qcut45' and not k.startswith('nj1')]
    a('4. **MLM (ESTIMATE: single generator).**')
    a(f'   - DJR, plan metric (max deviation from a quadratic fit within ±0.1 decade of qCut; E-INC 200/500/1000, Ẽ-INC 500, '
      f'V-MERGE 20/30 and 50/75): d01 {rng(d01, 1, False)}, d12 {rng(d12, 1, False)}. Above the plan\'s 10 %: {", ".join(pfails) or "none"} '
      '(this metric mixes fit inadequacy with steps). '
      + ' '.join(f'{k} is not in these ranges: its ME cut pT(QQ̄)_ME ≥ 100 GeV sculpts d01 around qCut by construction '
                 f'(d01 plan metric {100 * v["log10d01"]["max_dev_near_qcut"]:.1f} %, step test '
                 f'{pc(v["log10d01"]["step_at_qcut"]["disc"], 1)} ± {100 * v["log10d01"]["step_at_qcut"]["disc_err"]:.1f} %); '
                 'the trigger region is validated by the generation-cut closure below.' for k, v in xtrg.items()))
    a(f'   - DJR, local step test at qCut (two straight-line fits, §4.1): d01 {rng(st01)}, d12 {rng(st12)}; FAIL (> 10 %): '
      f'{", ".join(fails) or "none"}. ' + ('All nominal (30/45) samples PASS.' if not nom_fail else
                                           f'Nominal (30/45) FAIL: {", ".join(nom_fail)}.'))
    a(f'   - Merging-scale variation moves f(pT > 200) by {rng(fv)}; 0-1j vs 0-2j {pc(qv["nj1_xqcut30_qcut45"]["f_pt200"] / f0 - 1)} %.')
    clo = M['me_cut_closure']
    wr, ies, iss, ue = (TS['ranges'][k] for k in ('w_ratio_inc_trg', 'inc_event_share', 'inc_sigma_share', 'unweight_eff_tail'))
    mig = [v['migration_MEpt_lt100'] for v in clo.values()]; gc = [v['generation_cut_closure']['ratio_TRG_over_INC_MEge100'] for v in clo.values()]
    a(f'   - ME cut pT(QQ̄)_ME > 100 GeV misses {rng(mig, 1, False)} of the matched tail; the generation cut itself closes '
      f'({min(gc):.3f}-{max(gc):.3f}). Trigger samples are **stitched** (TRGS = TRG ∪ INC[pT_ME < 100]) and **shuffled**; their '
      f'INC rows carry {wr["min"]:.1f}-{wr["max"]:.1f}× the TRG weight ({100 * ies["min"]:.2f}-{100 * ies["max"]:.2f} % of the '
      f'tail events, {100 * iss["min"]:.1f}-{100 * iss["max"]:.1f} % of the tail σ), so weights are mandatory (loader returns '
      f'them; deterministic unweighting available, tail efficiency {100 * ue["min"]:.1f}-{100 * ue["max"]:.1f} %).')
    ip = I['points']['F_550']
    ipull = max(abs(ip[k]['pull']) for k in ('sigma_matched_fb', 'f_pt200', 'x_tail', 'nosc_tail'))
    a(f'   - Mass-interpolation closure at 550 GeV (V-INTERP vs 500/600): σ_matched {pc(ip["sigma_matched_fb"]["rel"])} ± '
      f'{100 * ip["sigma_matched_fb"]["err"]:.1f} %, f(pT>200) {pc(ip["f_pt200"]["rel"])} ± {100 * ip["f_pt200"]["err"]:.1f} %, '
      f'tail median ℓ_max {pc(ip["x_tail"]["rel"])} ± {100 * ip["x_tail"]["err"]:.1f} %, N_osc {pc(ip["nosc_tail"]["rel"])} ± '
      f'{100 * ip["nosc_tail"]["err"]:.1f} % (max |pull| {ipull:.1f}; precision limited by MC statistics).')
    # 5 tune / shower
    tr = T['comparisons']['TRG_CP5_vs_Monash']['rel_change_variation_over_nominal']
    vs = Sh['vshower_m500']
    vsig = max(abs(vs[d]['rel_to_nominal'][k] / vs[d]['rel_to_nominal'][k + '_stat']) for d in ('UP', 'DN')
               for k in ('f200', 'x_median', 'gm1_q84'))
    al = Sh['alps_and_scale9']
    fa05 = [al[p]['alps0p5']['rel_to_nominal']['f200'] for p in al]; fa2 = [al[p]['alps2']['rel_to_nominal']['f200'] for p in al]
    xa = [al[p][v]['rel_to_nominal']['x_median'] for p in al for v in ('alps0p5', 'alps2')]
    fs9 = [u for p in al for u in al[p]['scale9_envelope']['f200']]
    a('5. **Tune, MPI, shower and ISR-tail uncertainty (ESTIMATE).**')
    a(f'   - CP5 → Monash (TRG, 500 GeV): f(pT>200) {pc(tr["f_pt200"])} %, γ* tail median {pc(tr["gstar_tail"])} %, '
      f'leading-jet pT {pc(tr["j1pt"])} %; σ_matched {pc(tr["sigma"])} % (irrelevant: normalisation from K). MPI off: '
      f'|shift| ≤ {100 * max(abs(T["comparisons"]["TRG_MPIon_vs_off"]["rel_change_variation_over_nominal"][k]) for k in ("pt", "j1pt", "f_pt200", "gstar_tail", "nosc_tail")):.1f} % '
      'on pT(QQ̄), leading-jet pT, f(pT>200) and the γ*/N_osc tail medians.')
    a(f'   - V-SHOWER (Pythia ISR+FSR μ_R × ½ / × 2, 500 GeV): f(pT>200) {pc(vs["UP"]["rel_to_nominal"]["f200"])} / '
      f'{pc(vs["DN"]["rel_to_nominal"]["f200"])} ± {100 * vs["UP"]["rel_to_nominal"]["f200_stat"]:.1f} %, median ℓ_max '
      f'{pc(vs["UP"]["rel_to_nominal"]["x_median"])} / {pc(vs["DN"]["rel_to_nominal"]["x_median"])} ± '
      f'{100 * vs["UP"]["rel_to_nominal"]["x_median_stat"]:.1f} %, q84(γ*−1) {pc(vs["UP"]["rel_to_nominal"]["gm1_q84"])} / '
      f'{pc(vs["DN"]["rel_to_nominal"]["gm1_q84"])} % (all within {vsig:.1f}σ of zero).')
    a(f'   - ME emission α_s (MG `--alps` ×½ / ×2, E and Ẽ at 200/500/1000): f(pT>200) {rng(fa05, 0)} / {rng(fa2, 0)}; median '
      f'ℓ_max {rng(xa)}. The production 9-point (μ_R, μ_F) weights move f by only {rng(fs9)} (μ_F; they do not vary the emission α_s).')
    shw = max(abs(vs['UP']['rel_to_nominal']['f200']), abs(vs['DN']['rel_to_nominal']['f200']))
    up = [(al[p]['alps0p5']['rel_to_nominal']['f200'] ** 2 + max(fv) ** 2 + shw ** 2) ** 0.5 for p in al]
    dn = [(al[p]['alps2']['rel_to_nominal']['f200'] ** 2 + min(fv) ** 2 + shw ** 2) ** 0.5 for p in al]
    lops = [1 - L['points'][p]['f_pt200_LOPS'] / L['points'][p]['f_pt200_INC'] for p in PTS]
    a(f'   - **Tail-rate uncertainty of f(pT > 200) at LO-MLM: +{100 * min(up):.0f}…+{100 * max(up):.0f} % / −{100 * min(dn):.0f}…'
      f'−{100 * max(dn):.0f} %** (ME α_s ⊕ merging envelope ⊕ Pythia shower, quadrature; largest at 200 GeV). LO+PS is '
      f'{100 * min(lops):.0f}-{100 * max(lops):.0f} % below MLM. The **shape** (ℓ_max, γ* medians) is stable to ≈ ±{100 * max(sb):.0f} % '
      '(item 3). No NLO (FxFx) point: DEFERRED.md.')
    # 6 loader
    fn = [P['firstN_regression']['PASS'] for P in O['points'].values()]
    th_new = [P['new_MG']['thickness_um_q'][1] for P in O['points'].values()]; th_old = [P['old_LO_cache']['thickness_um_q'][1] for P in O['points'].values()]
    bit = all(v['all_kinematics_bitwise'] for v in RR.values())
    a('6. **Loader, interface and reproducibility (VERIFIED where stated).**')
    a(f'   - `run_causal` on 4 × 500 MG events: 0 failures; plane-thickness medians {min(th_new):.1f}-{max(th_new):.1f} µm vs '
      f'{min(th_old):.1f}-{max(th_old):.1f} µm with the old cache.')
    a(f'   - First-N regression check on the stitched files (INC share of w and weighted median of ℓ_max in the first 500/2000/5000 '
      f'events, weighted and unweighted, template/toy halves): {"PASS" if all(fn) else "FAIL"} at all {len(fn)} points.')
    tq = TS['template_toy']; lp = tq['loader_points']
    a(f'   - Template/toy halves (`tt_split`), weighted median of ℓ_max in the tail: toy vs template '
      + ', '.join(f'{p.replace("E_", "E ").replace("S_", "Ẽ ")} {pc(v["rel_diff_toy_vs_template"])} % (pull {v["pull"]:+.1f})'
                  for p, v in lp.items())
      + f'; over all {tq["ndf"]} TRGS files max |pull| {tq["max_abs_pull"]:.1f} ({tq["argmax_abs_pull"].replace("E_", "E ").replace("S_", "Ẽ ")}), '
      f'χ²/ndf = {tq["chi2"]:.1f}/{tq["ndf"]} (p = {tq["chi2_pvalue"]:.2f}): consistent (bootstrap errors; `results/trgs_stats.json`).')
    a(f'   - Regeneration of the full Pythia record from the kept LHE + stored card/seed (row map columns): '
      f'{"bit-for-bit" if bit else "NOT bit-for-bit"} in all kinematic columns for {len(RR)} test jobs (B-5).')
    # 7 statistics
    Y = X['trigger_yields_E']['rows']
    a('7. **Statistics.** Effective tail statistics N_eff (pT > 200, |η| < 2.5, Kish) of TRGS: '
      + ', '.join(f'{int(m)} GeV {Y[m]["neff_tail_TRGS"] / 1e3:.1f}k ({Y[m]["neff_over_N3iab_eps018"]:.1f}×)' for m in ('200', '300', '400', '500', '1000'))
      + ' (× = ratio to the expected 3 ab⁻¹ signal after a Knapen-like ε = 0.18). 200/300 GeV were topped up for this.')
    # 8 toolchain
    a('8. **Toolchain findings (VERIFIED).** MG 2.9.22 re-orders a tune given in its `pythia8_card` and `Tune:pp` resets '
      'PDF:pSet and the shower α_s (§8); our production runs Pythia itself. MG install: only the 13 Python bytecode files our runs '
      'created were removed and a dangling config comment was fixed (§8).')
    # 9 QED
    qt = [v['tail']['x_median_rel'] for v in Q['points'].values()]; qm = [v['tail']['x_mean_rel'] for v in Q['points'].values()]
    qte = [v['tail']['x_median_rel_err'] for v in Q['points'].values()]; qme = [v['tail']['x_mean_rel_err'] for v in Q['points'].values()]
    qbig = min(Q['points'].values(), key=lambda v: v['tail']['x_median_rel'])['tail']
    ph = Q['photons_LOPS500']
    a(f'9. **QED FSR off the quirks (plan D12) is NOT in the samples.** Pythia\'s `QEDshowerByOther` acts only on resonances '
      f'and the SLHA DECAY block resets the flag. With the fix (`cards/pythia8_quirk_qedfsr.dat`, opt-in) {100 * ph["frac_events_with_quirk_photon"]:.0f} % '
      f'of events radiate, P(E_γ > 5 GeV) = {100 * ph["P_Egamma_gt5"]:.1f} %; the tail median of ℓ_max shifts by {rng(qt)} '
      f'(paired bootstrap stat. error ±{100 * min(qte):.1f}…{100 * max(qte):.1f} % per point, one Pythia job each, so the spread '
      f'between points is consistent with statistics); the tail mean, more stable, shifts by {rng(qm)} (±{100 * min(qme):.1f}…'
      f'{100 * max(qme):.1f} %). **Default: the delivered samples have no QED FSR off the quirks. Pending user decision: '
      f're-shower (≈ 15 CPU-h, beyond the remaining budget) vs a one-sided ℓ_max systematic** (if chosen, state it as '
      f'{pc(qbig["x_median_rel"])} ± {100 * qbig["x_median_rel_err"]:.1f} % (stat), the largest median shift, or the mean '
      f'{rng(qm)}; not a bare −1 %).')
    txt = '\n'.join(out) + '\n'
    open(os.path.join(RES, 'headlines.md'), 'w').write(txt)
    p = os.path.join(SIM, 'VALIDATION.md')
    v = open(p).read()
    if BEGIN in v and END in v:
        v = v[:v.index(BEGIN) + len(BEGIN)] + '\n' + txt + v[v.index(END):]
        open(p, 'w').write(v)
        print('VALIDATION.md §0 regenerated')
    else:
        print('markers not found; wrote results/headlines.md only')
    print(txt)


if __name__ == '__main__':
    main()
