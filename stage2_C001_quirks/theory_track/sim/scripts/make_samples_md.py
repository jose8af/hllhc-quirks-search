"""make_samples_md.py -- write sim/SAMPLES.md (sample inventory) and results/samples.json from ../data/sim/npz/*.npz and the
task table of produce.py.  Run: pixi run -e ana python scripts/make_samples_md.py"""
import glob
import hashlib
import json
import os
import sys
import zlib

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from produce import TASKS, CHUNK, PROCS, PTCUT, SYST   # noqa
from vlib import DATA, SIM, RES   # noqa


def md5(p):
    h = hashlib.md5()
    with open(p, 'rb') as f:
        for b in iter(lambda: f.read(1 << 20), b''):
            h.update(b)
    return h.hexdigest()


def neff(w):
    return float(w.sum() ** 2 / np.sum(w ** 2)) if len(w) else 0.0


def main():
    xs = json.load(open(os.path.join(RES, 'xsec.json'))) if os.path.exists(os.path.join(RES, 'xsec.json')) else {}
    norm = xs.get('normalisation_E', {}).get('rows', {})
    normS = xs.get('normalisation_S', {})
    rows = []
    seen = set()
    for t in TASKS:
        if t['id'].startswith('P-'):
            continue
        base = zlib.crc32(t['id'].encode()) % 1000 * 100000
        for m in t['masses']:
            if (t['id'], m) in seen:
                continue
            seen.add((t['id'], m))
            p = os.path.join(DATA, 'npz', f'{t["id"]}_m{m}.npz')
            nch = (t['n'] + CHUNK - 1) // CHUNK
            r = dict(id=t['id'], proc=t['proc'], spin=t['proc'][0], m=m, n_lhe_planned=t['n'], tune=t['tune'],
                     xqcut=None if t['proc'].endswith('LOPS') else t['xq'], qcut=None if t['proc'].endswith('LOPS') else t['qc'],
                     mpi=t['mpi'], me_cut_ptQQ=PTCUT.get(t['proc']),
                     seeds=[json.load(open(d))['seed'] for d in sorted(glob.glob(os.path.join(DATA, 'npz', 'chunks', t['id'], f'm{m}_c*.done.json')),
                                                                        key=lambda q: int(q.rsplit('_c', 1)[1].split('.')[0]))]
                     or [base + 10 * m + ic + 1 for ic in range(nch)],
                     file=os.path.relpath(p, os.path.dirname(SIM)), done=os.path.exists(p))
            if r['done']:
                c = np.load(p, allow_pickle=False)
                w = c['w']; pt = c['pt_pair']
                r.update(n_lhe=int(c['nlhe']), n_kept=int(len(w)), n_w_nonzero=int(np.sum(w != 0)),
                         n_pt200=int(np.sum((w != 0) & (pt > 200))), n_pt200_eta25=int(np.sum((w != 0) & (pt > 200) & (np.abs(c['eta_pair']) < 2.5))),
                         sigma_lhe_fb=float(c['sigma_lhe_fb']), sigma_matched_fb=float(w.sum()),
                         sigma_pt200_fb=float(w[pt > 200].sum()), md5=md5(p), size_MB=os.path.getsize(p) / 1e6,
                         neff_pt200_eta25=neff(w[(w != 0) & (pt > 200) & (np.abs(c['eta_pair']) < 2.5)]),
                         lhe=sorted(os.path.relpath(f, os.path.dirname(SIM)) for f in glob.glob(os.path.join(DATA, 'lhe', t['id'], f'm{m}_c*.lhe.gz'))))
                if 'sigma_norm_fb' in c.files:
                    r['sigma_norm_nic2_fb'] = float(c['sigma_norm_fb'])
                elif r['spin'] == 'F' and str(m) in norm:
                    r['sigma_norm_nic2_fb'] = norm[str(m)]['sigma_norm_nic2_fb']
                elif r['spin'] == 'S' and str(m) in normS:
                    r['sigma_norm_nic2_fb'] = normS[str(m)]['sigma_norm_nic2_fb']
            rows.append(r)
    json.dump(dict(rows=rows, systematics_arguments=SYST, chunk=CHUNK), open(os.path.join(RES, 'samples.json'), 'w'), indent=1)
    L = ['# Stage-2 sample inventory (MG5_aMC 2.9.22 + Pythia 8.313), generated by `scripts/make_samples_md.py`', '',
         'All σ are LO, CT18NLO, **N_IC = 1** (multiply by N_IC = 2), in fb, MG Gμ EW scheme, unless the column says otherwise. '
         '`σ_matched` = Σw at the nominal merging scale (MLM, qCut 45 GeV unless stated). '
         '**`σ_norm (N_IC=2)`** = recommended normalisation for yields: N_IC = 2 × K(theory_signal_model §2.3) × LO(α = 1/127.9) '
         '(see VALIDATION.md §1.2); it is stored in every npz (`sigma_norm_fb`, with `sigma_ref_fb`) and in `SAMPLES_INDEX.json` '
         '(`_sigma_norm_fb`). Yield of a selection at 3 ab⁻¹ = 3000 fb⁻¹ × `sigma_norm_fb` × Σw_sel / `sigma_ref_fb` '
         '(`mg_events.sigma_norm_fb`). The loader\'s `sigma_lo_mlm_fb` (alias `sigma_fb`) is LO-MLM without K, 17-38 % lower: '
         'not a yield normalisation. '
         'Files: `data/sim/npz/<ID>_m<m>.npz` (format: `scripts/convert_hepmc.py` header; loader `scripts/mg_events.py`); '
         'LHE (with 104 systematics weights) in `data/sim/lhe/<ID>/`; MG/Pythia logs, banners and DJR histograms in '
         '`data/sim/aux/<ID>/`. Seeds: MG `iseed` per chunk (Pythia job j of a chunk: (iseed × 10 + j) mod 9e8 + 1).', '',
         '**Read before using the arrays directly.**',
         '- **Rows with w = 0 exist** (14.9-25.0 % of the rows of matched files, V-NJ1 … V-TUNE-TRG): events vetoed by MLM at the nominal qCut but kept '
         'for the qCut 67.5/90 weight variations. Always weight with `w` or use the loader (which drops them).',
         '- **Weights are not all equal**: in the stitched TRGS files the INC rows carry 3.7-9.6× the TRG per-event weight. '
         'Weight every summary with `w`, or use `iter_events(..., unweight=True)` (deterministic hit-or-miss).',
         '- **Weight columns** (`wvar`, names in `wvar_names`; fb per event, N_IC = 1): the **merged** columns '
         '`..._MERGING=<qCut>` (107: 9 (μ_R, μ_F) × 5 dynamical scales, 58 CT18NLO members, NNPDF23LO, and the in-weight qCut '
         '67.5/90 variations) are the physical ones; `Weight_MERGING=45.000` = `w`. The 104 `AUX_k` and `Weight` are the '
         '**unmerged LHE weights** (no MLM factor, non-zero on vetoed rows; their sums are 1.2-1.5 × σ_matched): AUX_k = LHE '
         'weight id k, with k = 1-44 the (μ_R, μ_F) ∈ {½,1,2}² × dynamical-scale {−1, 1 ΣpT, 2 H_T, 3 H_T/2, 4 √ŝ} '
         'variations (μ_R outermost; the central point is k = 45), k = 45 = central (CT18NLO member 0), k = 46-103 = CT18NLO '
         'members 1-58, k = 104 = NNPDF23_lo_as_0130_qed member 0; `Weight` = unmerged central. To use an unmerged column, '
         'multiply by the per-event merging factor w / AUX_45 (as `val_xsec.py` does for NNPDF23LO). Envelope recipes: '
         '9-point (or 7-point without the (½,2) corners) on the merged MUF/MUR columns; CT18 Hessian asymmetric, 90 % CL → 68 % '
         'by ÷ 1.645.',
         '- **Provenance and split** (all physics files): `chunk`, `ievt_lhe` (event in data/sim/lhe/<ID>/m<m>_c<chunk>.lhe.gz), '
         '`py8_job`, `ievt_job`, `py8_seed`; `scripts/reshower.py` regenerates the full particle record of any row '
         '(bit-for-bit, VALIDATION §6). `tt_split` = 0 (template) / 1 (toy): build templates and pseudo-data from different '
         'halves (`iter_events(..., split=...)`).',
         '- **Statistics**: `N_eff` = (Σw)²/Σw² (Kish) of the selection; quote it, not the raw count.', '',
         '**Not included in σ_norm** (all positive except NLO EW): inelastic γγ → QQ̄ +4.0-4.2 % of the K-corrected DY (T6, '
         'synthesis S-20; ESTIMATE); the infracolour Sommerfeld / threshold factor +5 to +15 % (TH §2.4/§5, no calculation '
         'exists; ESTIMATE); NLO EW −few % (UNVERIFIED). Nuisances on σ_norm: ±5 % K-transfer + EW-scheme (TH §2.4/§5), PDF4LHC21 '
         '±3.7 / 6.6 / 18.5 % at 200 / 500 / 1000 GeV (TH §2.3), extrapolated K beyond 1200 GeV ±2 % (ESTIMATE). Not simulated: '
         '|q| = 2 (S-17), γγ → QQ̄, QED FSR off the quirks (Pythia setting inactive; −0.1…−1.1 % (stat. ±0.5…0.8 %) on the tail '
         'median of 2(γ*−1), mean −0.4…−0.8 ± 0.2 %; default: not applied, pending user decision: re-shower ≈ 15 CPU-h vs '
         'one-sided systematic; VALIDATION §7). K(13.6 TeV) of TH §2.3 is applied at 14 TeV (TH assumption, < 1.5 %).', '',
         'Common settings: √s = 14 TeV; 5-flavour, massless b; `dynamical_scale_choice = -1`; Pythia8 CP5 (cards/pythia8_tune_CP5.dat) '
         'unless stated; MPI and hadronisation on; quirks stable (cards/pythia8_quirk_common.dat); vertex at origin; '
         f'systematics `{SYST}`; effective run cards in `cards/run_card_prod_*.dat`.', '',
         '| ID | spin | m [GeV] | tune | xqcut/qCut | MPI | ME cut | N_LHE | kept | w≠0 | pT>200 | pT>200,|η|<2.5 | N_eff(pT>200,|η|<2.5) | σ_LHE | σ_matched | σ(pT>200) | σ_norm (N_IC=2) | seeds | file (md5) |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for r in rows:
        if not r['done']:
            L.append(f"| {r['id']} | {r['spin']} | {r['m']} | {r['tune']} | {r['xqcut']}/{r['qcut']} | {r['mpi']} | {r['me_cut_ptQQ']} | (planned {r['n_lhe_planned']}) | — | — | — | — | — | — | — | — | — | {r['seeds']} | not produced |")
            continue
        sn = r.get('sigma_norm_nic2_fb')
        L.append(f"| {r['id']} | {r['spin']} | {r['m']} | {r['tune']} | {r['xqcut']}/{r['qcut']} | {'on' if r['mpi'] else 'off'} | "
                 f"{r['me_cut_ptQQ'] or '—'} | {r['n_lhe']} | {r['n_kept']} | {r['n_w_nonzero']} | {r['n_pt200']} | {r['n_pt200_eta25']} | {r['neff_pt200_eta25']:.0f} | "
                 f"{r['sigma_lhe_fb']:.4g} | {r['sigma_matched_fb']:.4g} | {r['sigma_pt200_fb']:.4g} | {sn and f'{sn:.4g}'} | "
                 f"{r['seeds']} | `{os.path.basename(r['file'])}` ({r['md5'][:8]}) |")
    L += ['', '## Stitched trigger-region samples (recommended for pT(QQ̄) > 200 GeV studies; loader alias `trig`)', '',
          '`<P>-TRGS_m<m>.npz` = `<P>-TRG` (ME cut pT(QQ̄)_ME ≥ 100 GeV) ∪ `<P>-INC` events with pT(QQ̄)_ME < 100 GeV (column `origin` = 0/1; '
          'weights unchanged). Built by `scripts/stitch_trg.py`; reason: VALIDATION.md §4.4 (4.0-7.1 % of the matched pT > 200 GeV '
          'cross section has a soft ME jet). **Rows are shuffled** with a recorded seed (`shuffle_seed`, `row_src`), so any '
          'prefix is a fair sample. **The INC rows carry 3.7-9.6× the per-event weight of the TRG rows** (column w/w_TRG below): '
          'use `w` (always returned by the loader as `info["w"]`) or `iter_events(..., unweight=True)`. TRGS and INC share the '
          'INC-complement rows, so they are not independent samples (the independent closure test is the generation-cut '
          'closure, VALIDATION §4.4). `sigma_ref_fb` = INC σ_matched; `nlhe` = N_LHE(TRG) + N_LHE(INC).', '',
          '| file | events | from INC | w≠0 & pT>200 | of which from INC | share of σ(pT>200,|η|<2.5) from INC | ⟨w_INC⟩/⟨w_TRG⟩ | N_eff(pT>200,|η|<2.5) | σ(pT>200) [fb, N_IC=1] |',
          '|---|---|---|---|---|---|---|---|---|']
    for p in sorted(glob.glob(os.path.join(DATA, 'npz', '*-TRGS_m*.npz')), key=lambda s: (s.split('/')[-1][0], int(s.split('_m')[-1][:-4]))):
        c = np.load(p, allow_pickle=False); w = c['w']; o = c['origin']; s = (w != 0) & (c['pt_pair'] > 200)
        se = s & (np.abs(c['eta_pair']) < 2.5)
        share = w[se & (o == 1)].sum() / w[se].sum()
        ratio = w[(w > 0) & (o == 1)].mean() / w[(w > 0) & (o == 0)].mean()
        L.append(f"| `{os.path.basename(p)}` | {len(w)} | {int(o.sum())} | {int(s.sum())} | {int((s & (o == 1)).sum())} | {100 * share:.1f} % | "
                 f"{ratio:.1f} | {neff(w[se]):.0f} | {w[c['pt_pair'] > 200].sum():.4g} |")
    vs = sorted(glob.glob(os.path.join(DATA, 'npz', 'V-SHOWER-*_m500.npz')))
    if vs:
        L += ['', '## V-SHOWER (Pythia ISR+FSR renormalisation-scale variation, 500 GeV; VALIDATION §5.1)', '',
              'Re-shower (`scripts/run_vshower.sh`, `scripts/reshower.py`) of the kept LHE of E-TRG / E-INC m500 chunk 0 (50k LHE each), '
              'same seeds and card except `SpaceShower:renormMultFac = TimeShower:renormMultFac` = 0.25 (UP: μ_R × ½) or 4 (DN: μ_R × 2). '
              'Nominal reference = the chunk-0 rows of `E-TRG_m500.npz` / `E-INC_m500.npz`. Cards and logs: `data/sim/aux/fixer/V-SHOWER-*`.', '',
              '| file | N_LHE | kept | σ_matched [fb] | md5 |', '|---|---|---|---|---|']
        for p in vs:
            c = np.load(p, allow_pickle=False)
            L.append(f"| `{os.path.basename(p)}` | {int(c['nlhe'])} | {len(c['w'])} | {c['w'].sum():.4g} | {md5(p)[:8]} |")
    L += ['', 'Index for the loader: `data/sim/SAMPLES_INDEX.json` (keys `{spin}_{m}_{ID}` and aliases `{spin}_{m}_{incl,trig,lops}`; '
          '`_sigma_norm_fb` per point). V-INTERP (E-INC settings at the off-grid mass 550 GeV) is the mass-interpolation closure '
          'sample (VALIDATION §4.5). Top-ups 2026-10-11 (review S2-R1 B-4): E-TRG/E-INC 200 GeV +100k LHE each (chunks 2-3), '
          'E-TRG 300 +40k (chunk 1), E-INC 300 +50k (chunk 1).',
          'Non-physics files are in `data/sim/npz/aux/`: pilot `P-INC_m500.npz` (2000 events, pipeline test) and `T2compat_cache.npz` '
          '(legacy-reader file written by `val_loader.py`, VALIDATION §6).']
    open(os.path.join(SIM, 'SAMPLES.md'), 'w').write('\n'.join(L) + '\n')
    print('wrote SAMPLES.md,', sum(r['done'] for r in rows), 'of', len(rows), 'points done')


if __name__ == '__main__':
    main()
