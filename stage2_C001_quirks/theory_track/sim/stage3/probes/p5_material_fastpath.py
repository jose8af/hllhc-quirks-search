"""p5_material_fastpath.py -- Stage-3 probe 5: does a vacuum fast path in the material kick speed up B+M runs, bit for bit?

The proposed Stage-3 kernel (plan §4.1) may add one optimisation: in _material_kick, return immediately when the endpoint
is inside the tracker volume (r < 118.5 cm, |z| < 293.5 cm) but in no slab shell.  material_at returns vacuum there and
_material_kick then changes nothing, so the result must be bit-identical; the saving is the momentum/beta arithmetic and
the call.  This probe GENERATES a patched copy of code/T3_causal.py (string replacement, written to
probes/_gen/T3_causal_fastmat.py; code/T3_causal.py is not touched), then compares hits/status/nsteps and the CPU time
(1 thread, interleaved) on 6 events at 3 and 10 keV, configurations BM and M, same seeds.
Run: nice pixi run python sim/stage3/probes/p5_material_fastpath.py  -> data/sim_stage3/probes/p5_material_fastpath.json
"""
import importlib, json, os, sys, time
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); TT = os.path.normpath(os.path.join(HERE, '..', '..', '..'))
GEN = os.path.join(HERE, '_gen'); os.makedirs(GEN, exist_ok=True)
src = open(os.path.join(TT, 'code', 'T3_causal.py')).read()
anchor = "    px = P[k, 1]; py = P[k, 2]; pz = P[k, 3]\n    p = np.sqrt(px * px + py * py + pz * pz)\n    if p <= 0.0 or dsx <= 0.0:"
assert src.count(anchor) == 1
fast = ("    xx = X[k, 1]; yy = X[k, 2]; azz = abs(X[k, 3])\n"
        "    rr = np.sqrt(xx * xx + yy * yy)\n"
        "    if rr < 118.5 and azz < 293.5:\n"
        "        hit_slab = False\n"
        "        for kk in range(slabs.shape[0]):\n"
        "            if abs(rr - slabs[kk, 0]) < 0.5 * slabs[kk, 2] and azz < slabs[kk, 3]:\n"
        "                hit_slab = True\n"
        "                break\n"
        "        if not hit_slab:\n"
        "            return\n")
patched = src.replace(anchor, fast + anchor).replace("if __name__ == '__main__':", "if False:")
patched = patched.replace("sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))",
                          f"sys.path.insert(0, {os.path.join(TT, 'code')!r})")
open(os.path.join(GEN, 'T3_causal_fastmat.py'), 'w').write('# GENERATED by p5_material_fastpath.py -- do not edit\n' + patched)
sys.path.insert(0, GEN); sys.path.insert(0, os.path.join(TT, 'code')); sys.path.insert(0, os.path.join(TT, 'sim', 'scripts'))
import mg_events as mg  # noqa
from T3_causal import run_causal as run_ref  # noqa
from T3_causal_fastmat import run_causal as run_fast  # noqa

ev = []
for e in mg.iter_events(500, 'trig', 'F', eta_max=2.5, ptmin=200.0, split='template', unweight=True):
    ev.append(e)
    if len(ev) == 6:
        break
run_ref(ev[0][0], ev[0][1], 500.0, 1.0); run_fast(ev[0][0], ev[0][1], 500.0, 1.0)
res = {}
for lam in (3.0, 10.0):
    for cfg, kw in (('BM', dict(B0=3.8112)), ('M', dict(B0=0.0))):
        tr = tf = 0.0; same = True; nst = 0
        for i, (p1, p2, info) in enumerate(ev):
            t0 = time.perf_counter(); a = run_ref(p1, p2, 500.0, lam, seed=101 + i, **kw); tr += time.perf_counter() - t0
            t0 = time.perf_counter(); b = run_fast(p1, p2, 500.0, lam, seed=101 + i, **kw); tf += time.perf_counter() - t0
            same &= bool(np.array_equal(a['hits'], b['hits']) and a['status'] == b['status'] and a['nsteps'] == b['nsteps']
                         and np.array_equal(a['P'], b['P']))
            nst += a['nsteps']
        res[f'{lam:g}keV_{cfg}'] = dict(t_ref=round(tr, 2), t_fast=round(tf, 2), speedup=round(tr / tf, 3), bit_identical=same,
                                       ns_per_step_ref=round(tr / nst * 1e9, 1), ns_per_step_fast=round(tf / nst * 1e9, 1))
        print(lam, cfg, res[f'{lam:g}keV_{cfg}'], flush=True)
json.dump(res, open(os.path.join(TT, 'data', 'sim_stage3', 'probes', 'p5_material_fastpath.json'), 'w'), indent=1)
