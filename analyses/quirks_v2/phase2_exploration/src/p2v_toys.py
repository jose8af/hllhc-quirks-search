CATS = ('SR_T', 'SR_G')
DEFAULTS = dict(backend='numpy', opt='scipy', strategy=None, tol=None, layout='std', start='std', stitch=0,
                fixneg=0.0, profile=0, record=0)


def synthetic(n_terms, n_nuis, seed):
    """Copy of p2c_t1.synthetic (sizes only, no study number)."""
    rng = np.random.default_rng(seed)
    names = [f'nu{j}' for j in range(n_nuis)]
    nuis = {n: {'bound': (1.5 if j % 4 == 3 else None)} for j, n in enumerate(names)}
    terms = []
    for t in range(n_terms):
        own = {names[j]: float(rng.uniform(0.02, 0.4)) for j in range(n_nuis) if j < 2 or (t + j) % 3 == 0}
        terms.append(dict(name=f't{t}', m=int(rng.choice([0, 0, 1, 1, 2, 3, 5, 8])),
                          kappa={c: float(rng.uniform(0.01, 0.3)) for c in CATS}, nuis=own))
    signal = {'yield': {'SR_T': 1.5, 'SR_G': 1.5}, 'nuis': {names[0]: 0.02, names[1]: 0.05}}
    return terms, nuis, signal


def normsys(ws):
    return [{'name': n, 'type': 'normsys', 'data': {'hi': float(np.exp(w)), 'lo': float(np.exp(-w))}}
            for n, w in ws.items()]


def build(terms, nuis, signal, layout='std', mu_max=1.0e3):
    """std: p2c_t1.build (one channel per category, one per auxiliary count).  merged: same terms in two channels."""
    channels = []; obs = []
    if layout == 'std':
        for c in CATS:
            samples = [{'name': 'signal', 'data': [float(signal['yield'][c])],
                        'modifiers': [{'name': 'mu', 'type': 'normfactor', 'data': None}] + normsys(signal['nuis'])}]
            for t in terms:
                if t['kappa'].get(c, 0.0) <= 0:
                    continue
                samples.append({'name': t['name'], 'data': [float(t['kappa'][c])],
                                'modifiers': [{'name': 'lam_' + t['name'], 'type': 'normfactor', 'data': None}]
                                + normsys(t['nuis'])})
            channels.append({'name': c, 'samples': samples}); obs.append({'name': c, 'data': [0.0]})
        for t in terms:
            channels.append({'name': 'aux_' + t['name'],
                             'samples': [{'name': 'count', 'data': [1.0],
                                          'modifiers': [{'name': 'lam_' + t['name'], 'type': 'normfactor', 'data': None}]}]})
            obs.append({'name': 'aux_' + t['name'], 'data': [float(t['m'])]})
    else:
        samples = [{'name': 'signal', 'data': [float(signal['yield'][c]) for c in CATS],
                    'modifiers': [{'name': 'mu', 'type': 'normfactor', 'data': None}] + normsys(signal['nuis'])}]
        for t in terms:
            samples.append({'name': t['name'], 'data': [float(t['kappa'].get(c, 0.0)) for c in CATS],
                            'modifiers': [{'name': 'lam_' + t['name'], 'type': 'normfactor', 'data': None}]
                            + normsys(t['nuis'])})
        channels.append({'name': 'SR', 'samples': samples}); obs.append({'name': 'SR', 'data': [0.0, 0.0]})
        n = len(terms)
        aux = [{'name': t['name'], 'data': [1.0 if j == i else 0.0 for j in range(n)],
                'modifiers': [{'name': 'lam_' + t['name'], 'type': 'normfactor', 'data': None}]}
               for i, t in enumerate(terms)]
        channels.append({'name': 'aux', 'samples': aux}); obs.append({'name': 'aux', 'data': [float(t['m']) for t in terms]})
    pars = [{'name': 'mu', 'bounds': [[0.0, float(mu_max)]], 'inits': [1.0]}]
    for t in terms:
        pars.append({'name': 'lam_' + t['name'], 'bounds': [[1e-9, 10.0 * (t['m'] + 5.0)]], 'inits': [t['m'] + 1.0]})
    for n, d in nuis.items():
        if d.get('bound') is not None:
            pars.append({'name': n, 'bounds': [[-5.0, float(d['bound'])]], 'inits': [0.0]})
    spec = {'version': '1.0.0', 'channels': channels, 'observations': obs,
            'measurements': [{'name': 'qv2', 'config': {'poi': 'mu', 'parameters': pars}}]}
    ws = pyhf.Workspace(spec)
    model = ws.model(modifier_settings={'normsys': {'interpcode': 'code1'}})
    return ws, model


class Truth:
    """Explicit numpy form of the model for the generation (independent of backend and layout)."""

    def __init__(self, terms, nuis, signal):
        self.terms, self.nuis, self.signal = terms, nuis, signal
        self.names = list(nuis)
        self.m = np.array([t['m'] for t in terms], float)
        self.kap = np.array([[t['kappa'].get(c, 0.0) for c in CATS] for t in terms])       # (T, 2)
        self.w_t = np.array([[t['nuis'].get(n, 0.0) for n in self.names] for t in terms])  # (T, K)
        self.w_s = np.array([signal['nuis'].get(n, 0.0) for n in self.names])
        self.s = np.array([signal['yield'][c] for c in CATS])
        self.bound = np.array([d['bound'] if d.get('bound') is not None else np.inf for d in nuis.values()])

    def draw(self, mu, rng):
        """RNG order of p2c_t1.generate: lambda per term, theta per nuisance, then n_T, n_G."""
        lam = np.array([rng.gamma(m + 1.0) for m in self.m])
        th = np.array([min(rng.normal(), b) for b in self.bound])
        exp = self.expected(mu, lam, th)
        n = np.array([rng.poisson(exp[0]), rng.poisson(exp[1])], float)
        return n, lam, th

    def expected(self, mu, lam, th):
        return mu * self.s * np.exp(self.w_s @ th) + (self.kap * (lam * np.exp(self.w_t @ th))[:, None]).sum(0)


def data_for(model, layout, n, m):
    """Full data vector (main + auxiliary data) in the model's channel order."""
    obs = {}
    if layout == 'std':
        obs['SR_T'], obs['SR_G'] = [n[0]], [n[1]]
        for i, mi in enumerate(m):
            obs[f'aux_t{i}'] = [mi]
    else:
        obs['SR'] = [n[0], n[1]]; obs['aux'] = list(m)
    return np.concatenate([np.concatenate([np.asarray(obs[c], float) for c in model.config.channels]),
                           np.asarray(model.config.auxdata, float)])


def par_vector(model, truth, mu, lam, th):
    cfg = model.config
    p = np.array(cfg.suggested_init(), float)
    p[cfg.poi_index] = mu
    for i, t in enumerate(truth.terms):
        p[cfg.par_slice('lam_' + t['name'])] = lam[i]
    for k, nm in enumerate(truth.names):
        p[cfg.par_slice(nm)] = th[k]
    return p


class FitStats:
    def __init__(self):
        self.rows = []

    def install(self):
        cls = type(pyhf.get_backend()[1])       # __slots__ class: patch the class, not the instance
        orig = cls._internal_minimize

        def wrapped(self_, *a, **k):
            c0 = time.process_time()
            try:
                r = orig(self_, *a, **k)
            except Exception:
                self.rows.append((0, -1, -1, -1, time.process_time() - c0))
                raise
            self.rows.append((1, int(getattr(r, 'nfev', -1) or -1), int(getattr(r, 'njev', -1) or -1),
                              int(getattr(r, 'nit', -1) or -1), time.process_time() - c0))
            return r
        cls._internal_minimize = wrapped

    def summary(self, rows):
        if not rows:
            return {}
        a = np.array(rows, float)
        ok = a[:, 0] == 1
        out = dict(n_fits=int(len(a)), n_fit_fail=int((~ok).sum()), cpu_s_per_fit_mean=float(a[:, 4].mean()))
        for j, k in ((1, 'nfev'), (2, 'njev'), (3, 'nit')):
            v = a[ok, j]
            v = v[v >= 0]
            if len(v):
                out[k] = dict(mean=float(v.mean()), median=float(np.median(v)), p90=float(np.quantile(v, 0.9)),
                              max=float(v.max()))
        return out


def main(argv):
    out, n_terms, n_nuis, n_toys, mu_test = argv[0], int(argv[1]), int(argv[2]), int(argv[3]), float(argv[4])
    conf = dict(DEFAULTS)
    if len(argv) > 5 and argv[5] not in ('', '-'):
        for kv in argv[5].split(','):
            k, v = kv.split('=')
            conf[k] = v
    seed = int(argv[6]) if len(argv) > 6 else 20261116
    toy_seed = int(argv[7]) if len(argv) > 7 else seed + 1      # seed + 1: the toy stream of p2c_t1 time mode
    conf['stitch'] = int(conf['stitch']); conf['fixneg'] = float(conf['fixneg']); conf['profile'] = int(conf['profile'])
    conf['record'] = int(conf['record'])
    okw = {}
    if conf['tol'] is not None:
        okw['tolerance'] = float(conf['tol'])
    if conf['opt'] == 'minuit':
        if conf['strategy'] is not None:
            okw['strategy'] = int(conf['strategy'])
        optimizer = pyhf.optimize.minuit_optimizer(**okw)
    else:
        optimizer = pyhf.optimize.scipy_optimizer(**okw)
    pyhf.set_backend(conf['backend'], optimizer)
    tl = pyhf.tensorlib
    stats = FitStats(); stats.install()

    terms, nuis, signal = synthetic(n_terms, n_nuis, seed)
    ws, model = build(terms, nuis, signal, layout=conf['layout'])
    cfg = model.config
    truth = Truth(terms, nuis, signal)
    init0 = list(cfg.suggested_init()); bounds = [list(b) for b in cfg.suggested_bounds()]
    fixed0 = list(cfg.suggested_fixed())
    fixed_terms = []
    if conf['fixneg'] > 0:      # OPTION ONLY (T1-f): fix the smallest contributions at m + 1
        contrib = truth.kap.sum(1) * (truth.m + 1.0)
        order = np.argsort(contrib); cum = np.cumsum(contrib[order]) / contrib.sum()
        fixed_terms = [int(i) for i, c in zip(order, cum) if c <= conf['fixneg']]
        for i in fixed_terms:
            j = cfg.par_slice('lam_' + terms[i]['name']).start
            fixed0[j] = True; init0[j] = truth.m[i] + 1.0
    use_direct = conf['start'] != 'std' or conf['stitch'] == 1 or conf['record'] == 1
    fkw = dict(do_stitch=True) if conf['stitch'] else {}

    def q_direct(data, init_fix, init_free):
        """pyhf _qmu_like with separate start values: fixed_poi_fit and fit, both pyhf."""
        pf, nll_fix = pyhf.infer.mle.fixed_poi_fit(mu_test, data, model, init_fix, bounds, fixed0,
                                                   return_fitted_val=True, **fkw)
        if init_free is None:
            init_free = tl.tolist(pf)
        pu, nll_free = pyhf.infer.mle.fit(data, model, init_free, bounds, fixed0, return_fitted_val=True, **fkw)
        q = float(np.clip(float(nll_fix) - float(nll_free), 0.0, None))
        muhat = float(tl.tolist(pu)[cfg.poi_index])
        state['rec'].append((float(nll_fix), float(nll_free), muhat))
        state['prevfix'] = tl.tolist(pf)
        return (0.0 if muhat > mu_test else q), tl.tolist(pu), muhat

    state = dict(prev=None, prevfix=None, rec=[])

    def q_of(data, gen_pars):
        if not use_direct:
            return float(pyhf.infer.test_statistics.qmu_tilde(mu_test, data, model, init0, bounds, fixed0)), None
        if conf['start'] == 'prev' and state['prev'] is not None:
            q, pu, muhat = q_direct(data, state['prev'], state['prev'])
        elif conf['start'] == 'prev2' and state['prev'] is not None:
            q, pu, muhat = q_direct(data, state['prevfix'], state['prev'])
        elif conf['start'] == 'chain':
            q, pu, muhat = q_direct(data, init0, None)
        else:
            q, pu, muhat = q_direct(data, init0, init0)
        state['prev'] = pu
        return q, muhat

    def one_toy(mu_gen, rng):
        n, lam, th = truth.draw(mu_gen, rng)
        data = tl.astensor(data_for(model, conf['layout'], n, truth.m))
        try:
            q, _ = q_of(data, None); return q, 0
        except Exception:  # noqa: BLE001 - a failed fit is counted, then retried once from the generated values
            state['rec'].append(None)
            gp = par_vector(model, truth, mu_gen, lam, th)
            ini = [float(np.clip(v, b[0], b[1])) for v, b in zip(gp, bounds)]
            for i in fixed_terms:
                j = cfg.par_slice('lam_' + terms[i]['name']).start; ini[j] = init0[j]
            try:
                q = float(pyhf.infer.test_statistics.qmu_tilde(mu_test, data, model, ini, bounds, fixed0))
                return q, 1
            except Exception:  # noqa: BLE001
                return None, 2

    # generation check against pyhf on one draw (separate RNG, not part of the paired stream)
    rc = np.random.default_rng(12345)
    n_chk, lam_c, th_c = truth.draw(2.0, rc)
    e_p = np.asarray(tl.tolist(model.expected_actualdata(tl.astensor(par_vector(model, truth, 2.0, lam_c, th_c)))))
    e_t = truth.expected(2.0, lam_c, th_c)
    if conf['layout'] == 'std':
        e_pm = np.array([e_p[cfg.channels.index('SR_T')], e_p[cfg.channels.index('SR_G')]])
    else:
        e_pm = e_p[cfg.channel_slices['SR']]
    gen_check = float(np.max(np.abs(e_pm / e_t - 1)))
    if gen_check > 1e-9:
        raise SystemExit(f'generation formula disagrees with pyhf: {gen_check}')
    # warm-up toy (jit compilation for jax), separate RNG, timed separately
    c0 = time.process_time(); w0 = time.time()
    one_toy(mu_test, np.random.default_rng(999))
    one_toy(0.0, np.random.default_rng(998))
    warm_cpu, warm_wall = time.process_time() - c0, time.time() - w0
    stats.rows.clear(); state['prev'] = None

    rng = np.random.default_rng(toy_seed)
    prof = cProfile.Profile() if conf['profile'] else None
    res = dict(n_par=cfg.npars, n_terms=n_terms, n_nuis=n_nuis, n_toys=n_toys, mu_test=mu_test, seed=seed,
               toy_seed=toy_seed, config=conf,
               fixed_terms=fixed_terms, channels=len(cfg.channels), bins=int(sum(cfg.channel_nbins.values())),
               samples=len(cfg.samples), pyhf=pyhf.__version__, numpy=np.__version__, gen_check=gen_check,
               warmup_cpu_s=warm_cpu, warmup_wall_s=warm_wall, host=os.uname().nodename)
    try:
        import jax
        res['jax'] = jax.__version__
    except ImportError:
        pass
    try:
        import iminuit
        res['iminuit'] = iminuit.__version__
    except ImportError:
        pass
    import scipy
    res['scipy'] = scipy.__version__
    qs = {}
    t_all = time.process_time()
    for label, mu_gen in (('sb', mu_test), ('b', 0.0)):
        state['prev'] = None; state['rec'] = []
        q = []; cpu = []; retried = dropped = 0
        nrow0 = len(stats.rows)
        c0 = time.process_time(); w0 = time.time()
        if prof:
            prof.enable()
        for _ in range(n_toys):
            t0 = time.process_time()
            v, st = one_toy(mu_gen, rng)
            cpu.append(time.process_time() - t0)
            retried += st == 1; dropped += st == 2
            q.append(v)
        if prof:
            prof.disable()
        ctot, wtot = time.process_time() - c0, time.time() - w0
        cpu = np.array(cpu)
        qs[label] = q
        res[label] = dict(cpu_s=ctot, wall_s=wtot, cpu_s_per_toy=ctot / n_toys,
                          cpu_per_toy_sd=float(cpu.std(ddof=1)) if n_toys > 1 else None,
                          cpu_per_toy_quantiles=[float(x) for x in np.quantile(cpu, [0.1, 0.5, 0.9, 1.0])],
                          retried=int(retried), dropped=int(dropped), q=q, fits=stats.summary(stats.rows[nrow0:]))
        if conf['record']:
            res[label]['nll_fix_free_muhat'] = state['rec']
        log.info('%s: %d toys, %.3f s per toy (CPU), %.3f wall, retried %d, dropped %d', label, n_toys, ctot / n_toys,
                 wtot / n_toys, retried, dropped)
    res['cpu_s_total'] = time.process_time() - t_all
    per = np.concatenate([[res['sb']['cpu_s_per_toy']], [res['b']['cpu_s_per_toy']]])
    res['cpu_s_per_1000_sb_plus_1000_b'] = float(1000.0 * per.sum())
    sd = np.sqrt((res['sb']['cpu_per_toy_sd'] or 0) ** 2 + (res['b']['cpu_per_toy_sd'] or 0) ** 2)
    res['cpu_s_per_1000_plus_1000_stat_err'] = float(1000.0 * sd / np.sqrt(n_toys))
    qsb = np.array([x for x in qs['sb'] if x is not None]); qb = np.array([x for x in qs['b'] if x is not None])
    if len(qsb) and len(qb):
        qobs = float(np.median(qb))
        psb = float(np.mean(qsb >= qobs)); pb1 = float(np.mean(qb >= qobs))
        cls = psb / max(pb1, 1e-12)
        err = cls * np.sqrt((psb * (1 - psb) / len(qsb)) / max(psb, 1e-12) ** 2
                            + (pb1 * (1 - pb1) / len(qb)) / max(pb1, 1e-12) ** 2)
        res['cls'] = dict(q_obs_median_b=qobs, p_sb=psb, one_minus_pb=pb1, cls=cls, cls_err=float(err))
        log.info('CLs at mu %.3g: %.4f +- %.4f (q_obs %.3f)', mu_test, cls, err, qobs)
    res['max_rss_mb'] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024
    if prof:
        s = io.StringIO(); pstats.Stats(prof, stream=s).sort_stats('tottime').print_stats(25)
        res['profile_tottime'] = s.getvalue().splitlines()[:60]
        s = io.StringIO(); pstats.Stats(prof, stream=s).sort_stats('cumulative').print_stats(30)
        res['profile_cumulative'] = s.getvalue().splitlines()[:70]
    with open(out + '.tmp', 'w') as f:
        json.dump(res, f, indent=1)
    os.replace(out + '.tmp', out)
    log.info('n_par %d %s: %.0f +- %.0f s per 1000 + 1000 toys at one mu', cfg.npars, argv[5] if len(argv) > 5 else '',
             res['cpu_s_per_1000_sb_plus_1000_b'], res['cpu_s_per_1000_plus_1000_stat_err'])


if __name__ == '__main__':
    main(sys.argv[1:])
