"""p2v_toys.py -- cost of the T1 hybrid toys (STR §4.11 pt 2 and 5) against the number of parameters, and remedies.
Executor Viktor, 2026-11-16.  Builder, generator convention and synthetic sizes copied from p2c_t1.py (Tatiana).

  <python> p2v_toys.py <out.json> <n_terms> <n_nuis> <n_toys> <mu> <config> [seed] [toy_seed]
  (seed fixes the synthetic workspace, as p2c_t1; toy_seed the pseudo-experiment stream, default seed + 1)

config: comma-separated key=value, defaults in DEFAULTS:
  backend   numpy | jax                       pyhf tensor backend
  opt       scipy | minuit                    pyhf optimiser (scipy = SLSQP)
  strategy  minuit strategy (default: pyhf's choice: 0 with gradient, 1 without)
  tol       optimiser tolerance (default: pyhf's default)
  layout    std | merged                      std: one channel per category and per auxiliary count (as p2c_t1);
                                              merged: one 2-bin signal-region channel and one n_terms-bin auxiliary
                                              channel; the same product of Poisson terms (same likelihood)
  start     std | chain | prev | prev2        std: pyhf qmu_tilde from the suggested init (m + 1 for lambda);
                                              chain: the free fit starts from the fixed-mu fit's result;
                                              prev: both fits start from the previous toy's free-fit result;
                                              prev2: fixed fit from the previous fixed-fit result, free fit from the
                                              previous free-fit result (same ensemble; reset per ensemble)
  stitch    0 | 1                             1: the fixed POI is removed from the parameter vector (pyhf do_stitch)
                                              instead of an SLSQP equality constraint
  fixneg    float (0)                         OPTION ONLY (changes the model, T1-f): fix the lambda of the terms with
                                              the smallest kappa_tot (m + 1) up to this cumulative fraction of the
                                              background, at m + 1
  profile   0 | 1                             cProfile the toy loop; top functions written to the output
  record    0 | 1                             store (twice-NLL fixed, twice-NLL free, mu_hat) per toy (direct fits,
                                              same formula as pyhf qmu_tilde)

Pseudo-data are generated by an explicit numpy formula of the model (n_c expectation = mu S_c prod e^{w theta} +
sum_t kappa_tc lambda_t prod e^{w theta}, normsys code1 = exponential), with the RNG order of p2c_t1.generate, and
checked against model.expected_actualdata on the first toy: every configuration sees the same pseudo-data
(paired comparison).  The test statistic is pyhf's q~_mu (two pyhf fits); for start != std or stitch = 1 the two
fits are called directly and pyhf's own formula of _qmu_like is applied (clip at 0; 0 if mu_hat > mu).
Failed fit: retried once from the generated parameter values, then dropped (rule of the T1-b run, Tatiana's log
13:47); counts reported.
"""
